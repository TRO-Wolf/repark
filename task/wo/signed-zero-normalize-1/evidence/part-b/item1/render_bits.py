from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEGS = (("RePark", "repark-276dc503-addendum.jsonl"), ("Spark", "spark-addendum.jsonl"))
GROUPS = ("nan-sign", "log")


def main() -> int:
    table: dict[tuple[str, str], dict[str, str]] = {}
    order: list[tuple[str, str]] = []
    for engine, name in LEGS:
        for line in (HERE / "raw" / name).read_text(encoding="utf-8").splitlines():
            record = json.loads(line)
            if record.get("record") != "cell" or record["group"] not in GROUPS:
                continue
            key = (record["cid"], record["route"] if engine == "RePark" else "spark")
            row = (record.get("rows") or [[None]])[0]
            bits = (record.get("bits") or [[None]])[0]
            shown = ", ".join(
                f"{v} ({b})" if b else str(v) for v, b in zip(row, bits, strict=False)
            )
            table.setdefault(record["cid"], {})[key[1]] = (
                shown if record["outcome"] == "ANSWERED" else record["outcome"]
            )
            if (record["cid"], "") not in order:
                order.append((record["cid"], ""))
    lines = [
        "# Item 1 addendum: NaN signs and the log family, first row with bit patterns",
        "",
        "Generated by `render_bits.py` from `raw/repark-276dc503-addendum.jsonl` and "
        "`raw/spark-addendum.jsonl`.",
        "",
        "| cell | RePark spark-sql | RePark native | Spark 4.1.2 |",
        "|---|---|---|---|",
    ]
    for cid, _ in order:
        cells = table[cid]
        name = cid.replace("|", "\\|")
        lines.append(
            f"| {name} | {cells.get('spark-sql', '')} | {cells.get('native', '')} | "
            f"{cells.get('spark', '')} |"
        )
    (HERE / "addendum" / "bits.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
