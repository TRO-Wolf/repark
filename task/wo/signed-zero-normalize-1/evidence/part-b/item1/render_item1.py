from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ROUTES = ("spark-sql", "typed", "native")
SPARK_MARKER = "normalizenanandzero"


def read(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


def plan_text(record: dict[str, Any]) -> str:
    if record["outcome"] != "ANSWERED":
        return f"{record['outcome']}: {(record.get('error') or {}).get('message', '')}"
    return "\n".join("\n".join(str(value) for value in row) for row in record["plan"])


def spark_marks(text: str) -> str:
    if "== Optimized Logical Plan ==" not in text or "== Physical Plan ==" not in text:
        return "-"
    rest = text.split("== Optimized Logical Plan ==", 1)[1]
    optimized, physical = rest.split("== Physical Plan ==", 1)
    return f"{optimized.lower().count(SPARK_MARKER)} / {physical.lower().count(SPARK_MARKER)}"


def render_plans(repark: Path, spark: Path, out: Path, base: str) -> None:
    explains: dict[tuple[str, str, str], dict[str, Any]] = {}
    order: list[tuple[str, str]] = []
    for path, engine in ((repark, "repark"), (spark, "spark")):
        for record in read(path):
            if record.get("record") != "explain":
                continue
            explains[(record["site"], record["route"], engine)] = record
            if (record["site"], record["seat"]) not in order:
                order.append((record["site"], record["seat"]))
    lines = [
        "# SIGNED-ZERO-NORMALIZE-1 part B item 1: plan shapes (D14, `Distinct::On`), verbatim",
        "",
        f"Generated by `render_item1.py` from `raw/repark-{base}-explain.jsonl` and "
        "`raw/spark-explain.jsonl`. RePark: "
        f"main `{base}`'s release build, `EXPLAIN` on the Spark door (`spark-sql`) and on native; "
        "the typed row is the "
        "facade's `DataFrame.explain(True)`. Spark 4.1.2: `EXPLAIN EXTENDED` (typed: "
        "`explain(True)`). Seed tables: "
        "step 0's `t` and `un`. The last column counts `normalizenanandzero` calls in Spark's "
        "optimized logical plan and in its physical plan: "
        "Spark's own float key normalisation (its optimizer rule `NormalizeFloatingNumbers`), "
        "aggregate keys are "
        "wrapped at physical planning, join and window keys in the optimizer; `-` means Spark "
        "printed no plan (an "
        "analysis error).",
        "",
        "| cell | node kind | RePark spark-sql | RePark typed | RePark native | Spark | Spark "
        "`normalizenanandzero` (optimized / physical) |",
        "|---|---|---|---|---|---|---|",
    ]
    for site, seat in order:
        cols = []
        for route in ROUTES:
            record = explains.get((site, route, "repark"))
            cols.append("" if record is None else record["outcome"])
        spark_record = explains.get(
            (site, "typed" if site.endswith("-typed") else "spark-sql", "spark")
        )
        spark_outcome = "" if spark_record is None else spark_record["outcome"]
        marks = "" if spark_record is None else spark_marks(plan_text(spark_record))
        lines.append(f"| {site} | {seat} | " + " | ".join(cols) + f" | {spark_outcome} | {marks} |")
    lines.append("")
    for site, seat in order:
        lines.append(f"## {site}: {seat}")
        lines.append("")
        for route in ROUTES:
            record = explains.get((site, route, "repark"))
            if record is None:
                continue
            lines.append(f"RePark `{route}`: `{record['text']}`")
            lines.append("")
            lines.append("```text")
            lines.append(plan_text(record))
            lines.append("```")
            lines.append("")
        spark_record = explains.get(
            (site, "typed" if site.endswith("-typed") else "spark-sql", "spark")
        )
        if spark_record is not None:
            lines.append(f"Spark 4.1.2: `{spark_record['text']}`")
            lines.append("")
            lines.append("```text")
            lines.append(plan_text(spark_record))
            lines.append("```")
            lines.append("")
    out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")


def render_spill(repark: Path, spark: Path, labels: Path, out: Path, base: str) -> None:
    truth = {(r["cid"]): r for r in read(spark) if r.get("record") == "cell"}
    label_of = {(r["cid"], r["route"]): r["label"] for r in read(labels) if r["engine"] == "repark"}
    header = next(r for r in read(repark) if r.get("record") == "leg")
    lines = [
        "# SIGNED-ZERO-NORMALIZE-1 part B item 1: float keys under spill (D16)",
        "",
        f"Generated by `render_item1.py` from `raw/repark-{base}-spill.jsonl` and "
        "`raw/spark-spill.jsonl`. RePark: "
        f"main `{base}`'s release build, both doors, a `FairSpillPool` of "
        f"`{header.get('facade_memory_limit')}` "
        f"(`datafusion.runtime.memory_limit`, set at build on each door) and "
        f"`datafusion.execution.target_partitions = {header.get('partitions')}`, on "
        f"{header.get('rows')} rows: "
        "`d` is `-0.0` when `id % 4 = 0`, `0.0` when `id % 4 = 1`, else `id`; `f` is `CAST(d AS "
        "FLOAT)`. Truth: Spark "
        "4.1.2 on the same rows (one-file Iceberg table, `spark.sql.shuffle.partitions = 4`, no "
        "memory limit). "
        "`spill_count` is the sum over the operators of one `EXPLAIN ANALYZE` run of the same "
        "statement; the answer is "
        "a separate run under the same pool. Labels are part A's `label_of`.",
        "",
        "| cell | door | label | truth | RePark | spill_count | spilling operators | join |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for record in read(repark):
        if record.get("record") != "cell":
            continue
        spark_record = truth.get(record["cid"])
        answer = (
            "; ".join(",".join(str(v) for v in row) for row in record["rows"])
            if record["outcome"] == "ANSWERED"
            else record["outcome"]
        )
        expected = (
            "; ".join(",".join(str(v) for v in row) for row in spark_record["rows"])
            if spark_record
            else "(none)"
        )
        spilling = sorted(
            {
                op
                for op, name, value in record["spill_counters"]
                if name == "spill_count" and float(value.replace(",", "")) > 0
            }
        )
        lines.append(
            f"| {record['cid'].replace('|', chr(92) + '|')} | {record['route']} | "
            f"{label_of.get((record['cid'], record['route']), '')} | {expected} | "
            f"{answer} | {record['spill_count']:g} | {', '.join(spilling)} | "
            f"{', '.join(record.get('join_operators') or [])} |"
        )
    lines.append("")
    lines.append("Statements (`{s}` is the spill table, `{k}` the key column):")
    lines.append("")
    seen = set()
    for record in read(repark):
        if record.get("record") == "cell" and record["site"] not in seen:
            seen.add(record["site"])
            lines.append(f"- {record['site']} ({record['seat']}): `{record['text']}`")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="276dc503")
    arguments = parser.parse_args()
    raw = HERE / "raw"
    render_plans(
        raw / f"repark-{arguments.base}-explain.jsonl",
        raw / "spark-explain.jsonl",
        HERE / "plans.md",
        arguments.base,
    )
    render_spill(
        raw / f"repark-{arguments.base}-spill.jsonl",
        raw / "spark-spill.jsonl",
        HERE / "new-cells" / "labels.jsonl",
        HERE / "spill.md",
        arguments.base,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
