from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any


def key_of(row: dict[str, Any]) -> tuple[str, ...]:
    return (
        row["cid"],
        row["route"],
        row.get("kind") or "",
        row.get("build") or "",
        row.get("engine") or "",
    )


def load(path: Path) -> dict[tuple[str, ...], dict[str, Any]]:
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            rows[key_of(row)] = row
    return rows


def cell(row: dict[str, Any]) -> str:
    return " ".join(str(part) for part in key_of(row)[:4] if part)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--head", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--base-name", required=True)
    parser.add_argument("--head-name", required=True)
    parser.add_argument("--title", required=True)
    args = parser.parse_args()
    base = load(args.base)
    head = load(args.head)
    moves = Counter()
    lines = [f"# {args.title}", ""]
    lines.append(
        f"Generated by `moves.py`: each cell's label on"
        f" `{args.base_name}` and on `{args.head_name}`."
    )
    lines.append("")
    only_base = sorted(set(base) - set(head))
    only_head = sorted(set(head) - set(base))
    controls = []
    others = []
    kept = []
    for key in sorted(set(base) & set(head)):
        before = base[key]["label"]
        after = head[key]["label"]
        moves[(before, after)] += 1
        if before == after and after != "EQUAL":
            kept.append(head[key])
        elif before == "EQUAL" and after != "EQUAL":
            controls.append((base[key], head[key]))
        elif before != after and after != "EQUAL":
            others.append((base[key], head[key]))
    lines.append(
        f"Cells on both builds: {len(set(base) & set(head))}; only on the"
        f" base: {len(only_base)}; only on the head: {len(only_head)}."
    )
    lines.append("")
    lines.append("## 1. Moves by label")
    lines.append("")
    lines.append(f"| `{args.base_name}` | `{args.head_name}` | cells |")
    lines.append("|---|---|---|")
    for (before, after), count in sorted(moves.items(), key=lambda item: (-item[1], item[0])):
        lines.append(f"| {before} | {after} | {count} |")
    lines.append("")
    lines.append("## 2. EQUAL on the base, not EQUAL on the head")
    lines.append("")
    if controls:
        lines.append("| cell | head label | truth | head answer |")
        lines.append("|---|---|---|---|")
        for _, after in controls:
            lines.append(
                f"| {cell(after)} | {after['label']} | {after.get('truth')}"
                f" | {after.get('repark')} |"
            )
    else:
        lines.append("None.")
    lines.append("")
    lines.append("## 3. Moved between two non-EQUAL labels")
    lines.append("")
    if others:
        lines.append("| cell | base label | head label | truth | head answer |")
        lines.append("|---|---|---|---|---|")
        for before, after in others:
            lines.append(
                f"| {cell(after)} | {before['label']} | {after['label']}"
                f" | {after.get('truth')} | {after.get('repark')} |"
            )
    else:
        lines.append("None.")
    lines.append("")
    lines.append("## 4. Not EQUAL on both builds, same label")
    lines.append("")
    lines.append("| cell | label | decimal twin | truth | head answer |")
    lines.append("|---|---|---|---|---|")
    for row in kept:
        lines.append(
            f"| {cell(row)} | {row['label']} | {row.get('decimal_twin')}"
            f" | {row.get('truth')} | {row.get('repark')} |"
        )
    lines.append("")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"both {len(set(base) & set(head))} controls {len(controls)}"
        f" others {len(others)} kept {len(kept)}"
    )
    for (before, after), count in sorted(moves.items(), key=lambda item: (-item[1], item[0])):
        print(before, "->", after, count)


if __name__ == "__main__":
    main()
