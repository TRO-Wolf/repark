import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import cells

raw = Path(sys.argv[1])
V = [json.loads(line) for line in (raw / "verdicts.jsonl").open()]
LETTER = {
    "EQUAL": "=",
    "FORMAT": "=",
    "TYPE": "T",
    "VALUE": "V",
    "REPARK_RAISES": "R",
    "SPARK_RAISES": "S",
    "BOTH_RAISE": "B",
    "READ_ERR": "E",
}


def letter(r: dict) -> str:
    v = r["verdict"]
    if v == "VALUE" and r.get("causes", {}).get("truncated_one_unit") and len(r["causes"]) == 1:
        return "t"
    return LETTER[v]


def pick(conf: str, ansi: str) -> dict:
    return {r["key"]: r for r in V if r["conf"] == conf and r["ansi"] == ansi}


out = ["# Grids (generated by `grids.py` from `verdicts.jsonl`)", ""]
out.append(
    "Letters: `=` equal (value and type), `T` type only, `t` value truncated by one unit at the "
    "result scale (type equal), `V` other value difference, `R` RePark raises where Spark "
    "answers, `S` Spark raises where RePark answers, `B` both raise, `-` not run."
)
out.append("")
cols = [cells.col_name(p, s) for p, s in cells.AVG_COLS]
groups = list(cells.NORMAL) + list(cells.BIG)
for ansi in ("true", "false"):
    for conf in ("base", "native"):
        sel = pick(conf, ansi)
        if not sel:
            continue
        out.append(f"## `avg` ungrouped, one group per cell ({conf}, ANSI {ansi})")
        out.append("")
        out.append("| group | " + " | ".join(cols) + " |")
        out.append("|---|" + "---|" * len(cols))
        for g in groups:
            row = []
            for c in cols:
                r = sel.get(f"avg/ungrouped/{c}/g{g}")
                row.append(letter(r) if r else "-")
            out.append(f"| g{g} | " + " | ".join(row) + " |")
        out.append("")
        forms = sorted({r["pos"] for r in sel.values() if r["family"] == "avg"} - {"ungrouped"})
        out.append(f"## `avg` forms by column ({conf}, ANSI {ansi})")
        out.append("")
        out.append("| door | form | " + " | ".join(cols) + " |")
        out.append("|---|---|" + "---|" * len(cols))
        for door in ("sql", "dataframe", "iceberg", "native"):
            for form in forms:
                row = []
                hit = False
                for c in cols:
                    cand = [
                        r
                        for r in sel.values()
                        if r["family"] == "avg"
                        and r["pos"] == form
                        and r["col"] == c
                        and r["door"] == door
                    ]
                    if cand:
                        hit = True
                        row.append("".join(sorted({letter(r) for r in cand})))
                    else:
                        row.append("-")
                if hit:
                    out.append(f"| {door} | {form} | " + " | ".join(row) + " |")
        out.append("")
dcols = [f"d{p}_{s}" for p, s in cells.DIV_COLS]
for ansi in ("true", "false"):
    for conf in ("base", "apl_false", "pmp_false", "native"):
        sel = pick(conf, ansi)
        if not sel:
            continue
        out.append(f"## Division and controls by column ({conf}, ANSI {ansi})")
        out.append("")
        out.append("| door | cell | " + " | ".join(dcols) + " |")
        out.append("|---|---|" + "---|" * len(dcols))
        rows = defaultdict(dict)
        for r in sel.values():
            if r["family"] not in ("div", "divctl") or r["col"] not in dcols:
                continue
            parts = r["key"].split("/")
            name = parts[1] if len(parts) < 4 else f"{parts[1]} {parts[3]}"
            rows[(r["door"], name)][r["col"]] = letter(r)
        for (door, name), byc in sorted(rows.items()):
            out.append(f"| {door} | {name} | " + " | ".join(byc.get(c, "-") for c in dcols) + " |")
        out.append("")
        out.append("Result types, Spark / RePark, `d10_2` and `d28_2`:")
        out.append("")
        for (door, name), _ in sorted(rows.items()):
            for c in ("d10_2", "d28_2"):
                bits = name.split(" ")
                fam = "divctl" if bits[0] in cells.CONTROL_OPS else "div"
                key = (
                    f"{'divdf' if door == 'dataframe' else 'div'}/{bits[0]}/{c}"
                    if len(bits) == 1
                    else f"{fam}/{bits[0]}/{c}/{bits[1]}"
                )
                r = sel.get(key)
                if r and r.get("spark_types") and r.get("repark_types"):
                    st, rt = r["spark_types"][-1], r["repark_types"][-1]
                    if st != rt:
                        out.append(f"- `{door} {name} {c}`: `{st}` / `{rt}`")
        out.append("")
tot = defaultdict(Counter)
for r in V:
    tot[(r["conf"], r["ansi"], r["family"], r["door"])][letter(r)] += 1
out.append("## Totals by run, family and door")
out.append("")
out.append("| conf | ANSI | family | door | cells | = | T | t | V | R | S | B |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
for k, c in sorted(tot.items()):
    out.append(
        f"| {' | '.join(k)} | {sum(c.values())} | "
        + " | ".join(str(c.get(x, 0)) for x in "=TtVRSB")
        + " |"
    )
(raw / "grids.md").write_text("\n".join(out) + "\n")
print(len(out))
