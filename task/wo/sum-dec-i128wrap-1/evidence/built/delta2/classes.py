def short(answer: object) -> str:
    text = answer if isinstance(answer, str) else json.dumps(answer)
    if text.startswith("ERR:"):
        named = [part for part in text.split(":") if part.isupper() and "_" in part]
        return "raises " + (named[0] if named else text.split(":", 3)[-1].strip()[:40])
    try:
        rows = json.loads(text)["rows"]
    except (ValueError, KeyError, TypeError):
        return text[:60]
    shown = [" · ".join(row) if isinstance(row, list) else str(row) for row in rows[:3]]
    return "; ".join(shown) + (" …" if len(rows) > 3 else "")


def section(title: str, rows: list[tuple[str, str, str]], counts: dict[str, int]) -> None:
    print(f"## {title}\n")
    print(", ".join(f"ANSI {mode}: **{n}**" for mode, n in counts.items()) + "\n")
    print("| ANSI | cell | Spark | RePark head |")
    print("|---|---|---|---|")
    for mode, key, answers in rows:
        print(f"| {mode} | `{key}` | {answers} |")
    print()


