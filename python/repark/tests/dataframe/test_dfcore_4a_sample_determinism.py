def test_sample_seed7_row_set_matches_pre_slice(spark: ReparkSession) -> None:
    """Seeded sample answers the pre-slice row set."""
    observed = sorted(row[0] for row in spark.range(1000).sample(0.3, seed=7).collect())
    assert observed == list(SAMPLE_IDS_030_SEED7)
    repeat = sorted(row[0] for row in spark.range(1000).sample(0.3, seed=7).collect())
    assert repeat == observed
