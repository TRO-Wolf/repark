def test_sample_by_seed7_row_set_matches_pre_slice(spark: ReparkSession) -> None:
    """Seeded stratified sample answers the pre-slice row set."""
    frame = spark.range(1000).select((F.col("id") % 5).alias("k"), F.col("id").alias("v"))
    fractions = {0: 0.5, 1: 0.5, 2: 0.5, 3: 0.5, 4: 0.5}
    observed = sorted(row[1] for row in frame.sampleBy("k", fractions, seed=7).collect())
    assert observed == list(STRATA_IDS_SEED7)
    repeat = sorted(row[1] for row in frame.sampleBy("k", fractions, seed=7).collect())
    assert repeat == observed
