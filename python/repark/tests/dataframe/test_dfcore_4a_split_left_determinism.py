def test_random_split_seed7_left_matches_pre_slice(spark: ReparkSession) -> None:
    """Seeded split left part answers the pre-slice row set; parts partition the frame."""
    parts = spark.range(1000).randomSplit([0.5, 0.5], seed=7)
    left = sorted(row[0] for row in parts[0].collect())
    right = sorted(row[0] for row in parts[1].collect())
    assert left == list(SPLIT_LEFT_IDS_HALF_SEED7)
    assert sorted(left + right) == list(range(1000))
