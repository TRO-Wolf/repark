"""Record TRY_CAST(x AS TIMESTAMP) for a microsecond, a nanosecond and a string.

RePark is the installed module. Spark is optional: pass ``--spark`` only under an
interpreter that has pyspark. The markdown writer reads both JSON files.
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path
from typing import Any

QUERIES = {
    "microsecond": "SELECT TRY_CAST(ts AS TIMESTAMP) AS v FROM ice.ns.src WHERE id = 1",
    "nanosecond": "SELECT TRY_CAST(ns AS TIMESTAMP) AS v FROM ice.ns.src WHERE id = 1",
    "string": "SELECT TRY_CAST('2026-01-02 03:04:05.123456' AS TIMESTAMP) AS v",
}


def logical_plan(spark: Any, statement: str) -> str:
    """Return the logical plan, or the error text."""
    import _ice_tsns_coercion_1_doors as doors

    try:
        rows = spark.sql(f"EXPLAIN {statement}").collect()
    except Exception as error:
        return doors.error_text(error)
    parts = [row["plan"] for row in rows if row["plan_type"] == "logical_plan"]
    return " ".join(" ".join(part.split()) for part in parts)[:500]


def one(spark: Any, statement: str) -> dict[str, Any]:
    """Return the type, text, tick and plan of ``statement``."""
    import _ice_tsns_coercion_1_doors as doors
    import pyarrow as pa

    plan = logical_plan(spark, statement)
    try:
        table = spark.sql(statement).toArrow()
    except Exception as error:
        return {"error": doors.error_text(error), "plan": plan}
    field = table.schema.field("v")
    column = table.column("v")
    tick = None
    if pa.types.is_timestamp(column.type) and column.null_count < len(column):
        tick = column.cast(pa.int64()).to_pylist()[0]
    value = column.to_pylist()[0]
    return {
        "type": str(field.type),
        "value": None if value is None else str(value),
        "tick": tick,
        "plan": plan,
    }


def record_repark(zone: str) -> dict[str, Any]:
    """Record the three TRY_CAST calls on RePark."""
    import _ice_tsns_coercion_1_doors as doors

    found: dict[str, Any] = {}
    with tempfile.TemporaryDirectory(prefix="tsns-coercion-try-") as scratch:
        spark = doors.open_session(zone, Path(scratch))
        try:
            for name, statement in QUERIES.items():
                found[name] = one(spark, statement)
        finally:
            spark.stop()
    return {"engine": "repark", "zone": zone, "cells": found}


def record_spark(zone: str, warehouse: str) -> dict[str, Any]:
    """Record Spark's analogues. Nanoseconds stand where TIMESTAMP_NTZ stands."""
    from pyspark.sql import SparkSession

    spark = (
        SparkSession.builder.master("local[1]")
        .config("spark.ui.enabled", "false")
        .config("spark.sql.session.timeZone", zone)
        .config("spark.sql.warehouse.dir", warehouse)
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")
    spark.sql(
        "CREATE OR REPLACE TEMP VIEW src AS SELECT "
        "TIMESTAMP '2026-01-02 03:04:05.123456' AS ts, "
        "TIMESTAMP_NTZ '2026-01-02 03:04:05.123456789' AS ns"
    )
    analogues = {
        "microsecond": "SELECT TRY_CAST(ts AS TIMESTAMP) AS v FROM src",
        "nanosecond": "SELECT TRY_CAST(ns AS TIMESTAMP) AS v FROM src",
        "string": QUERIES["string"],
    }
    found: dict[str, Any] = {}
    for name, statement in analogues.items():
        try:
            frame = spark.sql(statement)
            type_name = frame.schema["v"].dataType.simpleString()
            row = frame.collect()[0]
            found[name] = {"type": type_name, "value": None if row["v"] is None else str(row["v"])}
        except Exception as error:
            found[name] = {"error": str(error).splitlines()[-1][:240]}
    spark.stop()
    return {
        "engine": "spark",
        "spark": "4.1.2",
        "zone": zone,
        "note": "Spark has no nanosecond type; the nanosecond input is TIMESTAMP_NTZ.",
        "cells": found,
    }


def markdown(repark: dict[str, Any], spark: dict[str, Any]) -> str:
    """Return the comparison table."""
    lines = [
        "# TRY_CAST AS TIMESTAMP — ICE-TSNS-COERCION-1 slice 0",
        "",
        "Generated by `_record_ice_tsns_coercion_1_try_cast.py`. Do not edit by hand.",
        "",
        f"- RePark zone: `{repark.get('zone', '')}`",
        f"- Spark zone: `{spark.get('zone', '')}`",
        f"- {spark.get('note', '')}",
        "",
        "| input | repark type | repark value | repark tick | spark type | spark value |",
        "|---|---|---|---:|---|---|",
    ]
    for name in QUERIES:
        left = repark["cells"][name]
        right = spark["cells"][name]
        lines.append(
            f"| {name} | `{left.get('type', left.get('error', ''))}` | "
            f"`{left.get('value', '')}` | `{left.get('tick', '')}` | "
            f"`{right.get('type', right.get('error', ''))}` | `{right.get('value', '')}` |"
        )
    lines.extend(["", "## RePark logical plans", ""])
    for name in QUERIES:
        lines.append(f"- {name}: `{repark['cells'][name].get('plan', '')}`")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    """Write one engine's JSON, or the markdown from both JSON files."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--engine", choices=("repark", "spark", "markdown"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--zone", default="America/New_York")
    parser.add_argument("--warehouse", type=Path)
    parser.add_argument("--repark-json", type=Path)
    parser.add_argument("--spark-json", type=Path)
    args = parser.parse_args()
    if args.engine == "repark":
        payload = record_repark(args.zone)
    elif args.engine == "spark":
        if args.warehouse is None:
            raise SystemExit("spark needs --warehouse")
        payload = record_spark(args.zone, str(args.warehouse))
    else:
        if args.repark_json is None or args.spark_json is None:
            raise SystemExit("markdown needs both json files")
        repark = json.loads(args.repark_json.read_text(encoding="utf-8"))
        spark = json.loads(args.spark_json.read_text(encoding="utf-8"))
        args.output.write_text(markdown(repark, spark), encoding="utf-8")
        return
    args.output.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
