def test_random_split_seed7_right_matches_pre_slice(spark: ReparkSession) -> None:
    """Seeded split right part answers the pre-slice row set; parts stay disjoint."""
    parts = spark.range(1000).randomSplit([0.5, 0.5], seed=7)
    left = sorted(row[0] for row in parts[0].collect())
    right = sorted(row[0] for row in parts[1].collect())
    assert right == list(SPLIT_RIGHT_IDS_HALF_SEED7)
    assert set(left).isdisjoint(right)
    assert len(left) + len(right) == 1000
