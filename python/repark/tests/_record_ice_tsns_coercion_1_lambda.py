"""Record the analyzed plan of a lambda over an array of nanosecond values.

``EXPLAIN`` on this build returns the plan after the analyzer has finished.
The public surface does not show the plan before the first ``type_coercion``.
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path
from typing import Any

import _ice_tsns_coercion_1_doors as doors

STATEMENT = "SELECT transform(array(ns), x -> coalesce(x, NULL)) AS v FROM ice.ns.src WHERE id = 1"


def plans(spark: Any, statement: str) -> dict[str, str]:
    """Return each ``EXPLAIN`` plan_type for ``statement``."""
    rows = spark.sql(f"EXPLAIN {statement}").collect()
    found: dict[str, str] = {}
    for row in rows:
        found[str(row["plan_type"])] = str(row["plan"])
    return found


def result_type(spark: Any, statement: str) -> str:
    """Return the Arrow type of the lambda result."""
    table = spark.sql(statement).toArrow()
    return str(table.schema.field("v").type)


def markdown(payload: dict[str, Any]) -> str:
    """Return the lambda note."""
    logical = payload["plans"].get("logical_plan", "")
    lines = [
        "# Lambda variable — ICE-TSNS-COERCION-1 slice 0",
        "",
        "Generated by `_record_ice_tsns_coercion_1_lambda.py`. Do not edit by hand.",
        "",
        f"- Statement: `{payload['statement']}`",
        f"- Result type: `{payload['result_type']}`",
        "",
        "The public `EXPLAIN` logical plan is the plan after analysis. It does not",
        "show the plan before the first `type_coercion`. On this plan `x` is the",
        "argument of `__repark_narrow_timestamp_ns__`, which is the session rule that",
        "runs after that coercion, and the untyped NULL has become a microsecond",
        "`TimestampMicrosecond` null. So when that rule ran, `x` was already a",
        "nanosecond value. Whether the lambda binder typed `x` before the first",
        "coercion is not on this surface.",
        "",
        "A product hook that would answer it directly: a dump of the plan between",
        "analyzer rules, taken before the first `type_coercion`.",
        "",
        "## Logical plan",
        "",
        "```",
        logical.rstrip(),
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write the lambda JSON and markdown."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--markdown", type=Path, required=True)
    parser.add_argument("--zone", default="America/New_York")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="tsns-coercion-lambda-") as scratch:
        spark = doors.open_session(args.zone, Path(scratch))
        try:
            payload = {
                "zone": args.zone,
                "statement": STATEMENT,
                "result_type": result_type(spark, STATEMENT),
                "plans": plans(spark, STATEMENT),
            }
        finally:
            spark.stop()
    args.output.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")
    args.markdown.write_text(markdown(payload), encoding="utf-8")


if __name__ == "__main__":
    main()
