"""Record why the gate-open rate is not on the public EXPLAIN text.

``EXPLAIN`` prints scan names and projections. It does not print leaf field
types, so a statement that only reads ``id`` from a ``timestamp_ns`` table looks
the same as a scan of a table with no nanosecond column. The pandas
``datetime64[ns]`` count is a source scan of the facade tests, not a share of
executed statements.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import subprocess
import tempfile
from pathlib import Path
from typing import Any

import _ice_tsns_coercion_1_doors as doors
import pandas as pd

PROBES = (
    "SELECT ns FROM ice.ns.src",
    "SELECT id FROM ice.ns.src",
    "SELECT count(*) FROM ice.ns.src",
)


def logical_plan(spark: Any, statement: str) -> str:
    """Return the logical plan text of ``statement``."""
    rows = spark.sql(f"EXPLAIN {statement}").collect()
    parts = [row["plan"] for row in rows if row["plan_type"] == "logical_plan"]
    return "\n".join(parts)


def pandas_frame(spark: Any) -> tuple[str, str]:
    """Return the Arrow schema and explain text of one ``datetime64[ns]`` frame."""
    frame = pd.DataFrame({"t": pd.to_datetime(["2026-01-02 03:04:05.123456789"])})
    result = spark.createDataFrame(frame)
    schema = str(result.toArrow().schema)
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        result.explain(True)
    return schema, buffer.getvalue()


def repo_root(path: Path) -> Path:
    """Return the git root that contains ``path``."""
    text = subprocess.check_output(
        ["git", "-C", str(path), "rev-parse", "--show-toplevel"],
        text=True,
    )
    return Path(text.strip())


def tracked_python(root: Path) -> list[Path]:
    """Return Python files under ``root`` that git already tracks."""
    root = root.resolve()
    repo = repo_root(root)
    listed = subprocess.check_output(
        ["git", "-C", str(repo), "ls-files", "--", str(root.relative_to(repo))],
        text=True,
    )
    return [repo / line for line in listed.splitlines() if line.endswith(".py")]


def datetime_hits(roots: list[Path]) -> list[tuple[str, int, str]]:
    """Return ``datetime64[ns]`` lines in tracked Python under ``roots``."""
    found: list[tuple[str, int, str]] = []
    for root in roots:
        repo = repo_root(root)
        for path in tracked_python(root):
            for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
                if "datetime64[ns]" not in line:
                    continue
                found.append((str(path.relative_to(repo)), number, line.strip()))
    return found


def markdown(
    plans: list[tuple[str, str]],
    schema: str,
    explain: str,
    hits: list[tuple[str, int, str]],
) -> str:
    """Return the gate note."""
    lines = [
        "# Gate-open rate — ICE-TSNS-COERCION-1 slice 0",
        "",
        "Generated by `_record_ice_tsns_coercion_1_gate.py`. Do not edit by hand.",
        "",
        "The share of executed facade statements whose plan has a leaf",
        "`Timestamp(ns, _)` was not counted. The public `EXPLAIN` logical plan",
        "does not print leaf field types. A scan of `id` from a table that also",
        "holds `timestamp_ns` does not mention nanoseconds, and neither does a",
        "scan that projects the nanosecond column.",
        "",
        "The hook that would count it: the analyzed plan's leaf schemas, or one",
        "counter in the analyzer incremented when a leaf field is",
        "`Timestamp(Nanosecond, _)` at any depth, including a field the projection",
        "drops. `DataFrame.schema` is the output schema, so it misses that leaf.",
        "",
        "## EXPLAIN of a table that holds timestamp_ns",
        "",
    ]
    for statement, plan in plans:
        marked = "Timestamp(ns)" in plan or "timestamp[ns]" in plan
        lines.append(f"- `{statement}` mentions a nanosecond type: `{marked}`")
        lines.append("")
        lines.append("```")
        lines.append(plan.rstrip())
        lines.append("```")
        lines.append("")
    lines.extend(
        [
            "## pandas datetime64[ns]",
            "",
            "One `createDataFrame` of a pandas `datetime64[ns]` column scans as",
            f"`{schema}`. Its explain text also omits the field type:",
            "",
            "```",
            explain.rstrip(),
            "```",
            "",
            "Tracked Python lines that mention `datetime64[ns]`.",
            f"{len(hits)} lines. This is not a count of executed statements.",
            "",
            "| file | line | text |",
            "|---|---:|---|",
        ]
    )
    for path, number, text in hits:
        lines.append(f"| `{path}` | {number} | `{text.replace('|', '/')}` |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    """Write the gate note."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tests", type=Path, nargs="+", required=True)
    args = parser.parse_args()
    plans: list[tuple[str, str]] = []
    with tempfile.TemporaryDirectory(prefix="tsns-coercion-gate-") as scratch:
        spark = doors.open_session("UTC", Path(scratch))
        try:
            for statement in PROBES:
                plans.append((statement, logical_plan(spark, statement)))
            schema, explain = pandas_frame(spark)
        finally:
            spark.stop()
    hits = datetime_hits(list(args.tests))
    args.output.write_text(markdown(plans, schema, explain, hits), encoding="utf-8")


if __name__ == "__main__":
    main()
