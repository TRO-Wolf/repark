"""Seeded messy-CSV torture generator (family ``smartcsv``).

Grows the three-row inline messy-CSV example in the facade's smartCsv suite into a
generator-scale corpus. Every torture class is labeled in ``manifest.json``, and
``small()`` at the default 64 rows emits **every** labeled class — column-scoped
classes as columns, file-scoped classes as properties of the emitted CSV text.

Two scopes:

* **column** — visible in the typed table (``small()`` / ``data.parquet``).
* **file** — visible only in the CSV text: UTF-8 BOM, preamble lines, duplicate
  header names, ragged (short and long) rows, the delimiter zoo, and values that
  embed every candidate delimiter so quoting is exercised in all four schemes.

CSV is the battleground; parquet is typed truth. The CSV deliberately does NOT
round-trip to the parquet by naive parsing — that mismatch is the point of the
family. The determinism pin is the parquet, per the A3 table-identity contract.
"""

from __future__ import annotations

import argparse
import codecs
import csv
import io
import json
import logging
import random
import sys
import types
from collections.abc import Iterator
from pathlib import Path
from typing import Any, Final

import pyarrow as pa
import pyarrow.parquet as pq

LOGGER = logging.getLogger(__name__)

FAMILY: Final[str] = "smartcsv"
DEFAULT_CLI_ROWS: Final[int] = 1_000_000
DEFAULT_SEED: Final[int] = 42
SMALL_ROWS: Final[int] = 64
MAX_ROWS: Final[int] = 10_000_000
BATCH_SIZE: Final[int] = 4_096
DATA_PARQUET: Final[str] = "data.parquet"
MANIFEST_NAME: Final[str] = "manifest.json"

#: UTF-8 BOM prepended to every emitted CSV. Built from ``codecs`` rather than written as
#: a literal — an invisible character in source is a review trap.
BOM: Final[str] = codecs.BOM_UTF8.decode("utf-8")
#: Junk lines written above the header row; none of them contains a candidate delimiter.
PREAMBLE_LINES: Final[tuple[str, ...]] = (
    "NOTE: repark torture export v1",
    "# generated by repark-datasets family smartcsv",
)
#: Delimiter zoo — one CSV file per scheme, same logical rows in each.
DELIMITERS: Final[dict[str, str]] = {
    "comma": ",",
    "semicolon": ";",
    "tab": "\t",
    "pipe": "|",
}

#: Ragged rows. Short wins when a row index qualifies for both (e.g. row 137).
SHORT_EVERY: Final[int] = 11
SHORT_OFFSET: Final[int] = 5
LONG_EVERY: Final[int] = 13
LONG_OFFSET: Final[int] = 7
#: How many trailing cells a short row omits (the two ``ragged_tail_*`` columns).
SHORT_ROW_MISSING_CELLS: Final[int] = 2

#: CSV spellings smartCsv resolves to bool, paired with their typed truth.
BOOL_SPELLINGS: Final[tuple[tuple[str, bool], ...]] = (
    ("true", True),
    ("TRUE", True),
    ("t", True),
    ("T", True),
    ("false", False),
    ("FALSE", False),
    ("f", False),
    ("F", False),
)
#: Bool-ish spellings that are NOT bool tokens; they must stay strings.
YES_NO_TOKENS: Final[tuple[str, ...]] = ("yes", "no", "Y", "N", "Yes", "No")

#: Null spellings the smartCsv default token set recognizes (case-insensitive).
#: Mirrored here so the generator can compute typed truth; DS-4 binds it to the engine.
DEFAULT_NULL_TOKEN_FOLD: Final[frozenset[str]] = frozenset({"", "null", "none", "na", "n/a", "nan"})
RECOGNIZED_NULL_TOKENS: Final[tuple[str, ...]] = (
    "",
    "null",
    "NULL",
    "none",
    "None",
    "NA",
    "na",
    "n/a",
    "N/A",
    "nan",
    "NaN",
)
#: Null-ish spellings NOT in the default set — these survive as literal strings.
UNRECOGNIZED_NULL_TOKENS: Final[tuple[str, ...]] = ("-", "\\N", "(null)", "NIL", "missing", "ok")
NULL_TOKEN_CYCLE: Final[tuple[str, ...]] = RECOGNIZED_NULL_TOKENS + UNRECOGNIZED_NULL_TOKENS

CURRENCY_MARKS: Final[tuple[str, ...]] = ("$", "€", "£")
#: Decimal width variants: pure fraction, bare int, uniform scale, wide int digits, signs,
#: leading zeros — the decimal-union torture set.
DECIMAL_WIDTHS: Final[tuple[str, ...]] = (
    "0.001",
    "12345",
    "19.99",
    "250",
    "1234567890.12345",
    "-019.99",
    "+250",
)

#: The column name emitted TWICE in the CSV header row.
DUPLICATE_HEADER_NAME: Final[str] = "dup_label"

SCHEMA: Final[pa.Schema] = pa.schema(
    [
        pa.field("id", pa.int64(), nullable=False),
        pa.field("amount_currency", pa.string(), nullable=False),
        pa.field("amount_wide", pa.string(), nullable=False),
        pa.field("euro_decimal", pa.string(), nullable=False),
        pa.field("flag", pa.bool_(), nullable=False),
        pa.field("yes_no", pa.string(), nullable=False),
        pa.field("nullable_note", pa.string(), nullable=True),
        pa.field("embedded_delims", pa.string(), nullable=False),
        pa.field("dup_label", pa.string(), nullable=False),
        pa.field("dup_label_2", pa.string(), nullable=False),
        pa.field("ragged_tail_1", pa.string(), nullable=True),
        pa.field("ragged_tail_2", pa.string(), nullable=True),
    ]
)

_COLUMN_ORDER: Final[tuple[str, ...]] = tuple(field.name for field in SCHEMA)
#: CSV header row — ``dup_label`` appears twice on purpose (the reader dedupes it).
CSV_HEADER: Final[tuple[str, ...]] = tuple(
    DUPLICATE_HEADER_NAME if name == "dup_label_2" else name for name in _COLUMN_ORDER
)


def _bootstrap_repark_datasets() -> None:
    if "repark_datasets" in sys.modules:
        return
    datasets_dir = Path(__file__).resolve().parent.parent
    package = types.ModuleType("repark_datasets")
    package.__path__ = [str(datasets_dir)]  # type: ignore[attr-defined]
    sys.modules["repark_datasets"] = package


def _cache_mod() -> Any:
    _bootstrap_repark_datasets()
    import importlib

    return importlib.import_module("repark_datasets._cache")


def load_manifest() -> dict[str, Any]:
    """Return the checked-in class manifest (tests read this file, not a copy)."""
    path = Path(__file__).resolve().parent / MANIFEST_NAME
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        msg = f"manifest must be a JSON object: {path}"
        raise ValueError(msg)
    return payload


def csv_file_name(scheme: str) -> str:
    """File name for one delimiter scheme (``comma`` → ``data_comma.csv``)."""
    if scheme not in DELIMITERS:
        known = ", ".join(DELIMITERS)
        msg = f"unknown delimiter scheme {scheme!r}; expected one of: {known}"
        raise ValueError(msg)
    return f"data_{scheme}.csv"


def _validate(rows: int, seed: int) -> None:
    if not isinstance(rows, int) or isinstance(rows, bool) or rows < 1:
        msg = f"rows must be an integer >= 1; got {rows!r}"
        raise ValueError(msg)
    if rows > MAX_ROWS:
        msg = f"rows must be <= {MAX_ROWS}; got {rows}"
        raise ValueError(msg)
    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        msg = f"seed must be an integer >= 0; got {seed!r}"
        raise ValueError(msg)


def is_short_row(row_index: int) -> bool:
    """Whether this row omits its two trailing cells in the CSV."""
    return row_index % SHORT_EVERY == SHORT_OFFSET


def is_long_row(row_index: int) -> bool:
    """Whether this row carries one unlabeled overflow cell (short rows win ties)."""
    return not is_short_row(row_index) and row_index % LONG_EVERY == LONG_OFFSET


def null_token_for(row_index: int) -> str:
    """The ``nullable_note`` CSV token for this row (cycles the full token vocabulary)."""
    return NULL_TOKEN_CYCLE[row_index % len(NULL_TOKEN_CYCLE)]


def typed_note(token: str) -> str | None:
    """Typed truth for a ``nullable_note`` token: null when the default set recognizes it."""
    return None if token.lower() in DEFAULT_NULL_TOKEN_FOLD else token


def _build_row(rng: random.Random, row_index: int) -> tuple[dict[str, Any], list[str]]:
    """One row: (typed truth, CSV cells). CSV cell count varies for ragged rows."""
    mark = CURRENCY_MARKS[row_index % len(CURRENCY_MARKS)]
    whole = rng.randint(1, 9_999_999)
    cents = rng.randint(0, 99)
    amount_currency = f"{mark}{whole:,}.{cents:02d}"
    amount_wide = DECIMAL_WIDTHS[row_index % len(DECIMAL_WIDTHS)]
    euro_decimal = f"{rng.randint(1, 999)},{rng.randint(0, 99):02d}"
    bool_token, flag = BOOL_SPELLINGS[row_index % len(BOOL_SPELLINGS)]
    yes_no = YES_NO_TOKENS[row_index % len(YES_NO_TOKENS)]
    note_token = null_token_for(row_index)
    embedded = f"r{row_index},s;t\tu|v"
    dup_left = f"left-{row_index:04d}"
    dup_right = f"right-{row_index:04d}"
    tail_1 = f"tail1-{row_index:04d}"
    tail_2 = f"tail2-{row_index:04d}"
    short = is_short_row(row_index)

    typed: dict[str, Any] = {
        "id": int(row_index),
        "amount_currency": amount_currency,
        "amount_wide": amount_wide,
        "euro_decimal": euro_decimal,
        "flag": flag,
        "yes_no": yes_no,
        "nullable_note": typed_note(note_token),
        "embedded_delims": embedded,
        "dup_label": dup_left,
        "dup_label_2": dup_right,
        "ragged_tail_1": None if short else tail_1,
        "ragged_tail_2": None if short else tail_2,
    }
    cells: list[str] = [
        str(row_index),
        amount_currency,
        amount_wide,
        euro_decimal,
        bool_token,
        yes_no,
        note_token,
        embedded,
        dup_left,
        dup_right,
        tail_1,
        tail_2,
    ]
    if short:
        cells = cells[:-SHORT_ROW_MISSING_CELLS]
    elif is_long_row(row_index):
        cells.append(f"overflow-{row_index:04d}")
    return typed, cells


def _iter_batches(
    rows: int,
    seed: int,
    *,
    batch_size: int = BATCH_SIZE,
) -> Iterator[tuple[pa.RecordBatch, list[list[str]]]]:
    rng = random.Random(seed)
    start = 0
    while start < rows:
        end = min(start + batch_size, rows)
        typed_rows: list[dict[str, Any]] = []
        csv_rows: list[list[str]] = []
        for row_index in range(start, end):
            typed, cells = _build_row(rng, row_index)
            typed_rows.append(typed)
            csv_rows.append(cells)
        yield pa.RecordBatch.from_pylist(typed_rows, schema=SCHEMA), csv_rows
        start = end


def generate(rows: int, seed: int) -> pa.Table:
    """Build the typed-truth table for ``seed`` (no wall-clock entropy)."""
    _validate(rows, seed)
    batches = [batch for batch, _csv in _iter_batches(rows, seed)]
    return pa.Table.from_batches(batches, schema=SCHEMA)


def small(rows: int = SMALL_ROWS, seed: int = DEFAULT_SEED) -> pa.Table:
    """CI / test door. Defaults are the bound A9 values (64 rows, seed 42).

    At 64 rows every column-scoped class cycles fully: 8 bool spellings, 17 null
    tokens, 3 currency marks, 7 decimal widths, 6 yes/no spellings, and both
    ragged directions.
    """
    return generate(rows, seed)


def read_parquet(path: Path) -> pa.Table:
    """Read a generator parquet and cast to :data:`SCHEMA` (table-identity pin)."""
    return pq.read_table(path).cast(SCHEMA)


def render_csv(rows: int, seed: int, scheme: str) -> str:
    """Render one delimiter scheme's CSV text in memory (BOM + preamble + rows)."""
    _validate(rows, seed)
    if scheme not in DELIMITERS:
        known = ", ".join(DELIMITERS)
        msg = f"unknown delimiter scheme {scheme!r}; expected one of: {known}"
        raise ValueError(msg)
    buffer = io.StringIO()
    _write_csv_stream(buffer, rows=rows, seed=seed, scheme=scheme)
    return buffer.getvalue()


def _write_csv_stream(handle: Any, *, rows: int, seed: int, scheme: str) -> None:
    handle.write(BOM)
    for line in PREAMBLE_LINES:
        handle.write(f"{line}\n")
    writer = csv.writer(handle, delimiter=DELIMITERS[scheme], lineterminator="\n")
    writer.writerow(list(CSV_HEADER))
    for _batch, csv_rows in _iter_batches(rows, seed):
        writer.writerows(csv_rows)


def write_files(
    *,
    rows: int = DEFAULT_CLI_ROWS,
    seed: int = DEFAULT_SEED,
    out: Path | None = None,
) -> Path:
    """Write ``data.parquet`` (typed truth) + one CSV per delimiter scheme."""
    _validate(rows, seed)
    cache = _cache_mod()
    if out is None:
        out_dir = cache.family_cache_dir(FAMILY)
        root = cache.default_datasets_root()
    else:
        out_dir = Path(out)
        root = out_dir
    prepared = cache.prepare_output_dir(out_dir, root=root)
    parquet_path = prepared / DATA_PARQUET
    cache.refuse_symlink_file(parquet_path)
    for scheme in DELIMITERS:
        cache.refuse_symlink_file(prepared / csv_file_name(scheme))

    LOGGER.info("smartcsv: writing %s rows (seed=%s) → %s", rows, seed, prepared)
    with parquet_path.open("wb") as parquet_handle:
        writer = pq.ParquetWriter(parquet_handle, SCHEMA)
        try:
            for batch, _csv_rows in _iter_batches(rows, seed):
                writer.write_batch(batch)
        finally:
            writer.close()

    for scheme in DELIMITERS:
        csv_path = prepared / csv_file_name(scheme)
        with csv_path.open("w", encoding="utf-8", newline="") as csv_handle:
            _write_csv_stream(csv_handle, rows=rows, seed=seed, scheme=scheme)
    return prepared


def main(argv: list[str] | None = None) -> int:
    """CLI: ``--rows`` (default 1_000_000), ``--seed``, ``--out``."""
    parser = argparse.ArgumentParser(description="Generate the smartCsv torture dataset")
    parser.add_argument("--rows", type=int, default=DEFAULT_CLI_ROWS)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    try:
        written = write_files(rows=args.rows, seed=args.seed, out=args.out)
    except ValueError as error:
        print(f"usage error: {error}", file=sys.stderr)
        return 2
    print(written)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
