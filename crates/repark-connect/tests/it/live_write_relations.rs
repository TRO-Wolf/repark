#[derive(Clone, Copy)]
enum Outcome {
    Rows(u64),
    Sqlstate(&'static str),
    Identity(&'static str),
    Generated(&'static str),
    Denied,
}

#[derive(Clone, Copy)]
struct Property {
    name: &'static str,
    ddl: &'static str,
    target: &'static str,
    columns: &'static [&'static str],
    batch: fn() -> RecordBatch,
    fallback: Option<RowFallback>,
    outcome: Outcome,
    signature: &'static str,
    expect: &'static str,
}

