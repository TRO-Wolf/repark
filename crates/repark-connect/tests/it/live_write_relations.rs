type Written = (bool, Option<RowFallback>, Result<WriteReport, ConnectError>);

async fn put(
    store: &Store,
    request: WriteRequest,
    requested: WritePath,
    batch: &RecordBatch,
) -> Written {
    let mut writer = match request.open(store.pool(), requested, store.options).await {
        Ok(writer) => writer,
        Err(error) => return (false, None, Err(error)),
    };
    let fallback = writer.fallback();
    let outcome = match writer.write(batch).await {
        Ok(()) => writer.commit().await,
        Err(error) => Err(error),
    };
    (true, fallback, outcome)
}

fn judge(property: &Property, requested: WritePath, relation: &QualifiedRelation, got: Written) {
    let name = property.name;
    let (opened, fallback, outcome) = got;
    let refused = |refusal| Err(ConnectError::WriteRefused { refusal });
    let column = |column: &str| column.to_string();
    let expected_fallback = match requested {
        WritePath::Bulk if opened => property.fallback,
        _ => None,
    };
    assert_eq!(fallback, expected_fallback, "{name} {requested:?}");
    let path = match (requested, property.fallback) {
        (WritePath::Bulk, None) => WritePath::Bulk,
        _ => WritePath::Row,
    };
    match property.outcome {
        Outcome::Rows(rows) => {
            assert_eq!(
                outcome,
                Ok(WriteReport { path, rows }),
                "{name} {requested:?}"
            );
        }
        Outcome::Sqlstate(expected) => match outcome {
            Err(ConnectError::Server { sqlstate, .. }) => {
                assert_eq!(sqlstate, expected, "{name} {requested:?}");
            }
            other => panic!("{name} {requested:?}: expected {expected}, got {other:?}"),
        },
        Outcome::Identity(name) => {
            let column = column(name);
            assert_eq!(outcome, refused(WriteRefusal::IdentityAlways { column }));
        }
        Outcome::Generated(name) => {
            let column = column(name);
            assert_eq!(outcome, refused(WriteRefusal::GeneratedColumn { column }));
        }
        Outcome::Denied => {
            let (relation, privilege) = (relation.clone(), Privilege::Insert);
            let denied = ConnectError::PermissionDenied {
                relation,
                privilege,
            };
            assert_eq!(outcome, Err(denied), "{name} {requested:?}");
        }
    }
}

async fn measure(cell: &Cell, owner: &Store, writer: &Store, extra: &str, property: &Property) {
    let mut signatures = Vec::new();
    for (requested, twin) in [(WritePath::Bulk, "b"), (WritePath::Row, "r")] {
        let table = format!("{}_{twin}", property.name);
        let fill = |template: &str| {
            template
                .replace("{s}", &cell.schema)
                .replace("{t}", &table)
                .replace("{x}", extra)
        };
        cell.sql(&fill(property.ddl)).await;
        let target = fill(property.target);
        let resolved = owner.target(cell, &target).await;
        let indexes: Vec<usize> = property
            .columns
            .iter()
            .map(|name| {
                let found = resolved
                    .columns
                    .iter()
                    .position(|c| c.name.as_str() == *name);
                found.expect("a column of the target")
            })
            .collect();
        let request = WriteRequest::new(&resolved)
            .expect("a relation takes rows")
            .columns(&indexes)
            .expect("the named columns");
        let relation = request.relation().clone();
        let got = put(writer, request, requested, &(property.batch)()).await;
        judge(property, requested, &relation, got);
        let signature = fill(property.signature);
        let row = cell.admin.query_one(signature.as_str(), &[]).await;
        let seen: Option<String> = row.expect(&signature).get(0);
        signatures.push(seen.unwrap_or_default());
    }
    assert_eq!(
        signatures[0], signatures[1],
        "{}: the twins differ",
        property.name
    );
    assert_eq!(signatures[0], property.expect, "{}", property.name);
}

async fn measure_all(properties: &[Property]) {
    let cell = Cell::open().await;
    let store = Store::new(&cell.settings(&[]));
    for property in properties {
        measure(&cell, &store, &store, "", property).await;
    }
    drop(store);
    no_backend_remains(&cell).await;
    cell.close().await;
}

