def tracked_maps(repo: Path) -> list[str]:
    """Every tracked `map.md`, repo-relative posix, sorted."""
    listed = subprocess.run(
        ["git", "-C", str(repo), "ls-files", "-z"], capture_output=True, check=True, text=True
    )
    return sorted(
        entry for entry in listed.stdout.split("\0") if entry and Path(entry).name == MAP_NAME
    )


def measure(repo: Path, path: str) -> tuple[int, int]:
    """(lines, bytes) of one map."""
    raw = (repo / path).read_bytes()
    return len(raw.decode("utf-8").splitlines()), len(raw)


def merge_base(repo: Path) -> str | None:
    """The merge base of HEAD with MAIN_REF, or None when git cannot name one."""
    try:
        found = subprocess.run(
            ["git", "-C", str(repo), "merge-base", "HEAD", MAIN_REF],
            capture_output=True,
            check=True,
            text=True,
        )
    except (subprocess.CalledProcessError, OSError):
        return None
    return found.stdout.strip() or None


def base_sizes(repo: Path, base: str | None, paths: list[str]) -> dict[str, tuple[int, int]]:
    """(lines, bytes) at `base` of each path that exists there as UTF-8 text."""
    sizes: dict[str, tuple[int, int]] = {}
    if base is None:
        return sizes
    for path in paths:
        shown = subprocess.run(
            ["git", "-C", str(repo), "show", f"{base}:{path}"], capture_output=True, check=False
        )
        if shown.returncode != 0:
            continue
        try:
            sizes[path] = (len(shown.stdout.decode("utf-8").splitlines()), len(shown.stdout))
        except UnicodeDecodeError:
            continue
    return sizes


def allowance(baseline: tuple[int, int], at_base: tuple[int, int] | None) -> tuple[int, int]:
    """The largest (lines, bytes) an excepted map may reach: its row, or its merge-base size
    where that is larger, measure by measure."""
    if at_base is None:
        return baseline
    return max(baseline[0], at_base[0]), max(baseline[1], at_base[1])


def matches(pattern: str, path: str) -> bool:
    """Whether `path` matches `pattern`, one path segment per `*`."""
    parts, globs = path.split("/"), pattern.split("/")
    return len(parts) == len(globs) and all(
        fnmatch.fnmatchcase(part, glob) for part, glob in zip(parts, globs, strict=True)
    )


def exempt(path: str) -> bool:
    """Whether a map is an exempt lifecycle inventory, by name or by pattern."""
    return path in EXEMPT or any(matches(pattern, path) for pattern in EXEMPT_PATTERNS)


def over(lines: int, size: int) -> bool:
    """Whether a measure crosses either ceiling."""
    return lines > DEFAULT_LINES or size > DEFAULT_BYTES


def check_map(
    path: str,
    lines: int,
    size: int,
    table: dict[str, tuple[int, int]],
    at_base: tuple[int, int] | None = None,
) -> list[str]:
    """Findings for one map against the ceilings, its baseline and its merge-base size."""
    baseline = table.get(path)
    if baseline is None:
        if not over(lines, size):
            return []
        return [
            f"ERROR: {path} is {lines} lines and {size} bytes (ceilings {DEFAULT_LINES} lines, "
            f"{DEFAULT_BYTES} bytes). Condense the map or split the directory; a new "
            "EXCEPTIONS row needs explicit owner approval."
        ]
    base_lines, base_bytes = baseline
    if not over(base_lines, base_bytes):
        return [f"ERROR: {path}: baseline ({base_lines}, {base_bytes}) is within both ceilings."]
    allowed_lines, allowed_bytes = allowance(baseline, at_base)
    if lines > allowed_lines or size > allowed_bytes:
        merged = (
            "" if at_base is None else f"; {at_base[0]} lines, {at_base[1]} bytes at the merge base"
        )
        return [
            f"ERROR: {path} grew to {lines} lines and {size} bytes (exact baseline "
            f"{base_lines} lines, {base_bytes} bytes{merged}). Make the edit size-neutral or "
            "condense the map; a raised baseline needs explicit owner approval."
        ]
    if lines <= base_lines and size <= base_bytes and (lines, size) != baseline:
        action = "delete the row" if not over(lines, size) else "lower the row"
        return [
            f"ERROR: {path} shrank to {lines} lines and {size} bytes below its exact baseline "
            f"{base_lines} lines, {base_bytes} bytes; {action} "
            "(python3 scripts/check_map_size.py --update-baselines)."
        ]
    return []


def render_row(path: str, lines: int, size: int) -> list[str]:
    """One EXCEPTIONS row as ruff formats it."""
    single = f'    "{path}": ({lines}, {size}),'
    if len(single) <= LINE_LIMIT:
        return [single]
    return [f'    "{path}": (', f"        {lines},", f"        {size},", "    ),"]


def rewrite_table(script: Path, rows: dict[str, tuple[int, int]]) -> None:
    """Replace the EXCEPTIONS literal in this script's source with `rows`."""
    source = script.read_text(encoding="utf-8").split("\n")
    start = next(index for index, line in enumerate(source) if line.startswith(TABLE_OPEN))
    end = start if source[start] == TABLE_OPEN + TABLE_CLOSE else source.index(TABLE_CLOSE, start)
    body = [line for path in sorted(rows) for line in render_row(path, *rows[path])]
    table = [TABLE_OPEN, *body, TABLE_CLOSE] if body else [TABLE_OPEN + TABLE_CLOSE]
    script.write_text("\n".join([*source[:start], *table, *source[end + 1 :]]), encoding="utf-8")


def update_baselines(
    repo: Path,
    measured: dict[str, tuple[int, int]],
    script: Path,
    at_base: dict[str, tuple[int, int]],
) -> int:
    """Rewrite EXCEPTIONS to the tree, never above a row's merge-base allowance; refuses growth
    past it and new violators."""
    refused: list[str] = []
    rows: dict[str, tuple[int, int]] = {}
    for path, (lines, size) in measured.items():
        if exempt(path):
            continue
        baseline = EXCEPTIONS.get(path)
        if baseline is None:
            if over(lines, size):
                refused.append(f"{path}: {lines} lines, {size} bytes, not excepted")
            continue
        allowed = allowance(baseline, at_base.get(path))
        if lines > allowed[0] or size > allowed[1]:
            refused.append(f"{path}: grew to {lines} lines, {size} bytes past {allowed}")
            continue
        if over(lines, size):
            rows[path] = (lines, size)
    if refused:
        for line in refused:
            print(f"REFUSED: {line}", file=sys.stderr)
        print("map-size: --update-baselines refused; nothing written", file=sys.stderr)
        return 1
    rewrite_table(script, rows)
    print(f"map-size: EXCEPTIONS rewritten in {script.relative_to(repo)} ({len(rows)} rows)")
    return 0


def run(repo: Path, update: bool) -> int:
    """Measure every map, then check or ratchet the table."""
    try:
        maps = tracked_maps(repo)
    except (subprocess.CalledProcessError, OSError) as error:
        print(f"ERROR: cannot list tracked files ({error})", file=sys.stderr)
        return 2
    if not maps:
        print("ERROR: no tracked map.md found — refuse to pass closed", file=sys.stderr)
        return 2
    measured: dict[str, tuple[int, int]] = {}
    for path in maps:
        try:
            measured[path] = measure(repo, path)
        except (OSError, UnicodeDecodeError) as error:
            print(f"ERROR: {path}: unreadable ({error})", file=sys.stderr)
            return 2
    errors = [
        f"ERROR: EXCEPTIONS key is no tracked map: {path} (delete the row)"
        for path in sorted(EXCEPTIONS)
        if path not in measured
    ]
    errors.extend(
        f"ERROR: EXEMPT key is no tracked map: {path} (delete the row)"
        for path in sorted(EXEMPT)
        if path not in measured
    )
    errors.extend(
        f"ERROR: {path} is both exempt and in EXCEPTIONS (delete the EXCEPTIONS row)"
        for path in sorted(EXCEPTIONS)
        if exempt(path)
    )
    at_base = base_sizes(repo, merge_base(repo), sorted(set(EXCEPTIONS) & set(measured)))
    if update:
        if errors:
            for error in errors:
                print(error, file=sys.stderr)
            return 1
        return update_baselines(repo, measured, Path(__file__).resolve(), at_base)
    for path, (lines, size) in measured.items():
        if not exempt(path):
            errors.extend(check_map(path, lines, size, EXCEPTIONS, at_base.get(path)))
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print(f"map-size: FAIL — {len(errors)} finding(s) across {len(maps)} maps", file=sys.stderr)
        return 1
    print(
        f"map-size: {len(maps)} maps clean (ceilings {DEFAULT_LINES} lines, {DEFAULT_BYTES} "
        f"bytes; {len(EXCEPTIONS)} exceptions, {sum(exempt(path) for path in maps)} exempt)"
    )
    return 0


def main() -> int:
    """CLI: `--update-baselines`, and the hidden `--repo` for the tests."""
    parser = argparse.ArgumentParser(prog="check_map_size.py", description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--update-baselines",
        action="store_true",
        help="rewrite EXCEPTIONS rows to the tree, up to the merge-base size; refuses growth",
    )
    parser.add_argument(
        "--repo", type=Path, default=Path(__file__).resolve().parent.parent, help=argparse.SUPPRESS
    )
    arguments = parser.parse_args()
    return run(arguments.repo.resolve(), arguments.update_baselines)


if __name__ == "__main__":
    sys.exit(main())
